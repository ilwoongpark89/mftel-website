// graphite ramp by contour level; the hottest pair (l=10) is the page's ember element
function strokeFor(level: number): string {
    if (level >= 10) return "#EA580C"; // ember-600 — non-text accent
    if (level >= 7) return "#A8A29E"; // stone-400
    if (level >= 3) return "#D6D3D1"; // stone-300
    return "#E7E5E4"; // stone-200
}

